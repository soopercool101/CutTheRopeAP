        public static bool Validate(out string errorMessage)
        {
            var contentDirectory = Path.Combine(Variables.GameDirectory, "content");
            if (!Directory.Exists(contentDirectory))
            {
                errorMessage = "content directory is missing! Please follow the setup guide!";
                return false;
            }

            errorMessage = "Your content directory does not match the official release! Please follow the setup guide!";
            var mapDirectory = Path.Combine(contentDirectory, "maps");
            if (!Directory.Exists(mapDirectory) || !Directory.Exists(Path.Combine(contentDirectory, "sounds")) || !Directory.Exists(Path.Combine(contentDirectory, "video")) || !Directory.Exists(Path.Combine(contentDirectory, "video_hd")))
            {
                return false;
            }

            var fileIndex = 0;
            if (new DirectoryInfo(mapDirectory).GetFiles().Length != 275)
            {
                return false;
            }
            // Map files are the most important, ensure their hashes match vanilla
            for (var i = 1; i <= 11; i++)
            {
                for (var j = 1; j <= 25; j++)
                {
                    var mapFile = Path.Combine(mapDirectory, $"{i}_{j}.xml");
                    if (!File.Exists(mapFile))
                    {
                        return false;
                    }
                    using (var md5 = System.Security.Cryptography.MD5.Create())
                    {
                        using (var stream = File.OpenRead(mapFile))
                        {
                            var hash = BitConverter.ToString(md5.ComputeHash(stream)).Replace("-", "");
                            if (!hash.Equals(MapHashes[fileIndex++]))
                            {
                                errorMessage =
                                    $"Your content directory does not match the official release! Hash mismatch for {i}_{j}.xml!";
                                return false;
                            }
                        }
                    }
                }
            }

            return true;
        }
